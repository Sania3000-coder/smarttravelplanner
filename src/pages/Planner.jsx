function ItineraryDisplay({ text }) {
  const lines = text.split("\n");

  function formatBold(line) {
    return line.split(/(\*\*.*?\*\*)/g).map((part, index) => {
      if (part.startsWith("**") && part.endsWith("**")) {
        return (
          <strong key={index} style={{ color: "#102a43", fontWeight: 800 }}>
            {part.slice(2, -2)}
          </strong>
        );
      }
      return part;
    });
  }

  return (
    <div style={styles.itineraryContainer}>
      {lines.map((line, index) => {
        const cleanLine = line.trim();

        if (!cleanLine) return null;

        const normalized = cleanLine
          .replace(/^#+\s*/, "")
          .replace(/\*\*/g, "")
          .trim();

        // Day-wise headings
        if (/^DAY\s*[1-7]\b/i.test(normalized)) {
          return (
            <div key={index} style={styles.dayHeading}>
              ✨ {normalized}
            </div>
          );
        }

        // Main headings
        if (
          cleanLine.startsWith("#") ||
          /^[🌍🏝️📅🍽️🏨🚕💰🎒✈️🧳⭐🌤️🗺️📌🎯]/u.test(normalized) ||
          /^(DESTINATION OVERVIEW|TOP ATTRACTIONS|LOCAL FOOD|HOTEL|ACCOMMODATION|LOCAL TRANSPORT|COMPLETE BUDGET|BUDGET BREAKDOWN|IMPORTANT TRAVEL TIPS|FINAL TRAVEL RECOMMENDATION)/i.test(normalized)
        ) {
          return (
            <h2 key={index} style={styles.sectionHeading}>
              {formatBold(normalized)}
            </h2>
          );
        }

        // Bullet points
        if (/^[-*•]\s*/.test(cleanLine)) {
          return (
            <div key={index} style={styles.bulletItem}>
              <span style={styles.bulletIcon}>✦</span>
              <span>{formatBold(cleanLine.replace(/^[-*•]\s*/, ""))}</span>
            </div>
          );
        }

        // Numbered points
        if (/^\d+[.)]\s*/.test(cleanLine)) {
          return (
            <div key={index} style={styles.bulletItem}>
              <span style={styles.bulletIcon}>➤</span>
              <span>{formatBold(cleanLine.replace(/^\d+[.)]\s*/, ""))}</span>
            </div>
          );
        }

        // Normal paragraphs
        return (
          <p key={index} style={styles.paragraph}>
            {formatBold(cleanLine)}
          </p>
        );
      })}
    </div>
  );
}

function Planner() {
  const location = useLocation();
  const autoGeneratedRef = useRef("");

  const [destination, setDestination] = useState(
    location.state?.destination || ""
  );

  const [days, setDays] = useState("3");
  const [budget, setBudget] = useState("");
  const [travelers, setTravelers] = useState("2");
  const [planned, setPlanned] = useState(false);
  const [loading, setLoading] = useState(false);
  const [message, setMessage] = useState("");

  // AI itinerary states
  const [itinerary, setItinerary] = useState("");
  const [generatingPlan, setGeneratingPlan] = useState(false);
  const [planError, setPlanError] = useState("");

  // Automatically generate itinerary from destination page
  useEffect(() => {
    const selectedDestination = location.state?.destination;

    if (!location.state?.autoGenerate || !selectedDestination) {
      return;
    }

    const requestKey = `${location.key}-${selectedDestination}`;

    if (autoGeneratedRef.current === requestKey) {
      return;
    }

    autoGeneratedRef.current = requestKey;

    setDestination(selectedDestination);
    setDays("3");
    setTravelers("2");
    setItinerary("");
    setPlanError("");
    setGeneratingPlan(true);

    async function generateItinerary() {
      const prompt = `
Act as a professional travel guide and AI trip planner.

Create a detailed, attractive and practical 3-day travel itinerary for ${selectedDestination}, India, for 2 travelers.

IMPORTANT:
Do not provide short or basic information.
Give detailed, realistic and useful recommendations.

Follow this structure:

🌍 DESTINATION OVERVIEW
- Detailed introduction
- Why this destination is famous
- Best time to visit
- Weather and travel conditions

🏝️ TOP ATTRACTIONS
- Famous tourist places
- What makes each place special
- Entry fees if known

📅 DAY-WISE TRAVEL ITINERARY

DAY 1 - Exploration and Sightseeing
- Morning activities
- Afternoon activities
- Evening activities

DAY 2 - Adventure and Local Experiences
- Morning activities
- Afternoon activities
- Evening activities

DAY 3 - Shopping and Relaxation
- Morning activities
- Afternoon activities
- Evening activities

🍽️ LOCAL FOOD AND RESTAURANTS
- Famous local dishes
- Popular food areas
- Food recommendations

🏨 HOTEL AND ACCOMMODATION
- Budget accommodation
- Mid-range accommodation
- Approximate hotel prices

🚕 LOCAL TRANSPORT
- Available transport options
- Approximate travel costs
- Useful transport tips

💰 COMPLETE BUDGET BREAKDOWN
- Hotel expenses
- Food expenses
- Transport expenses
- Activities and sightseeing
- Total estimated cost for 2 travelers

🎒 IMPORTANT TRAVEL TIPS
- Safety tips
- Things to carry
- Local guidelines
- Money-saving suggestions

⭐ FINAL TRAVEL RECOMMENDATION
Give a helpful conclusion.

FORMATTING RULES:
- Use clear headings and subheadings.
- Use **bold text** for important information.
- Use bullet points.
- Keep each day clearly separated.
- Highlight important prices and recommendations.
- Use Indian Rupees (₹).
- Keep language simple, informative and professional.
- Do not invent exact prices or hotel availability.
- Clearly mention that prices are approximate and may change.
- Do not ask follow-up questions.
      `;

      try {
        const response = await fetch(
          "http://localhost:5000/api/chatbot",
          {
            method: "POST",
            headers: {
              "Content-Type": "application/json"
            },
            body: JSON.stringify({
              message: prompt,
              history: []
            })
          }
        );

        const data = await response.json();

        if (!response.ok) {
          throw new Error(
            data.message ||
            data.error ||
            "Unable to generate itinerary."
          );
        }

        if (!data.reply) {
          throw new Error(
            "AI did not return a travel plan. Please try again."
          );
        }

        setItinerary(data.reply);

      } catch (error) {
        setPlanError(
          error.message || "Something went wrong. Please try again."
        );
        autoGeneratedRef.current = "";
      } finally {
        setGeneratingPlan(false);
      }
    }

    generateItinerary();
  }, [location.state, location.key]);

  async function handleSubmit(e) {
    e.preventDefault();

    if (
      !destination.trim() ||
      !budget ||
      Number(budget) <= 0
    ) {
      setMessage("Please enter destination and a valid budget!");
      return;
    }

    const token = localStorage.getItem("token");

    if (!token) {
      setMessage("Please login first to save your trip!");
      return;
    }

    try {
      setLoading(true);
      setMessage("");
      setPlanned(false);

      const response = await fetch(
        "http://localhost:5000/api/trips/save",
        {
          method: "POST",
          headers: {
            "Content-Type": "application/json",
            Authorization: `Bearer ${token}`
          },
          body: JSON.stringify({
            destination: destination.trim(),
            days,
            travelers,
            budget
          })
        }
      );

      const data = await response.json();

      if (!response.ok) {
        throw new Error(data.message || "Unable to save trip");
      }

      setPlanned(true);
      setMessage("Your trip has been saved successfully! ❤️");

    } catch (error) {
      setMessage(error.message || "Server connection failed!");
    } finally {
      setLoading(false);
    }
  }

  return (
    <div style={styles.page}>

      {/* HERO SECTION */}
      <div style={styles.hero}>
        <div>
          <span style={styles.tag}>
            ✈ YOUR NEXT ADVENTURE STARTS HERE
          </span>

          <h1 style={styles.heading}>
            Plan Your Dream{" "}
            <span style={{ color: "#ff7547" }}>Trip!</span>
          </h1>

          <p style={styles.subtitle}>
            Create your perfect journey. Choose your destination,
            set your budget and get ready to explore.
          </p>
        </div>

        <div style={styles.heroIcon}>🌍</div>
      </div>

      {/* AI GENERATED ITINERARY */}
      {location.state?.autoGenerate ? (

        <div style={styles.aiCard}>

          <div style={styles.aiHeader}>
            <span style={styles.aiIcon}>✨</span>

            <div>
              <h2 style={styles.aiTitle}>
                Your AI Travel Itinerary
              </h2>

              <p style={styles.aiSubtitle}>
                Your personalized trip to {destination}
              </p>
            </div>
          </div>

          <div style={styles.tripInfo}>
            <span style={styles.infoBadge}>📍 {destination}</span>
            <span style={styles.infoBadge}>📅 3 Days</span>
            <span style={styles.infoBadge}>👥 2 Travelers</span>
            <span style={styles.infoBadge}>🤖 AI Generated</span>
          </div>

          {generatingPlan && (
            <div style={styles.loadingBox}>
              <div style={styles.loadingIcon}>✈️</div>

              <h3>Creating Your Dream Trip...</h3>

              <p>
                TravelBuddy is preparing your detailed itinerary,
                attractions, food, hotels and estimated budget.
              </p>
            </div>
          )}

          {planError && (
            <div style={styles.errorBox}>
              <h3>Unable to generate your itinerary</h3>

              <p>{planError}</p>

              <button
                style={styles.retryButton}
                onClick={() => {
                  autoGeneratedRef.current = "";
                  setPlanError("");
                  setItinerary("");
                  setGeneratingPlan(false);
                }}
              >
                Please go back and try again
              </button>
            </div>
          )}

          {itinerary && (
            <ItineraryDisplay text={itinerary} />
          )}

          <div style={styles.aiNote}>
            💡 Note: All prices and recommendations are estimates.
            Please verify current rates before booking.
          </div>

        </div>

      ) : (

        <>
          {/* TRIP FORM */}
          <div style={styles.layout}>

            <div style={styles.formCard}>
              <h2 style={styles.formTitle}>
                🧳 Create Your Travel Plan
              </h2>

              <p style={styles.formSubtitle}>
                Fill in your travel details below
              </p>

              <form onSubmit={handleSubmit}>

                <label style={styles.label}>
                  📍 Destination
                </label>

                <input
                  style={styles.input}
                  value={destination}
                  onChange={(e) => setDestination(e.target.value)}
                  placeholder="e.g. Manali, Goa, Jaipur"
                  required
                />

                <div style={styles.twoColumns}>

                  <div>
                    <label style={styles.label}>
                      📅 Number of days
                    </label>

                    <select
                      style={styles.input}
                      value={days}
                      onChange={(e) => setDays(e.target.value)}
                    >
                      <option value="1">1 day</option>
                      <option value="2">2 days</option>
                      <option value="3">3 days</option>
                      <option value="5">5 days</option>
                      <option value="7">7 days</option>
                    </select>
                  </div>

                  <div>
                    <label style={styles.label}>
                      👥 Travelers
                    </label>

                    <input
                      style={styles.input}
                      type="number"
                      min="1"
                      value={travelers}
                      onChange={(e) => setTravelers(e.target.value)}
                      required
                    />
                  </div>

                </div>

                <label style={styles.label}>
                  💰 Total Budget (₹)
                </label>

                <input
                  style={styles.input}
                  type="number"
                  min="1"
                  value={budget}
                  onChange={(e) => setBudget(e.target.value)}
                  placeholder="Enter your total budget"
                  required
                />

                <button
                  type="submit"
                  style={{
                    ...styles.button,
                    opacity: loading ? 0.7 : 1
                  }}
                  disabled={loading}
                >
                  {loading
                    ? "Saving Your Trip..."
                    : "Create My Trip ✨"}
                </button>

              </form>

              {message && (
                <p
                  style={{
                    ...styles.message,
                    color: planned ? "#16834a" : "#d04435"
                  }}
                >
                  {message}
                </p>
              )}

            </div>

            {/* SIDE PANEL */}
            <div style={styles.sidePanel}>

              <div style={styles.travelIcon}>🏝️</div>

              <h2>Travel Without Limits</h2>

              <p>
                Every journey begins with a plan. Make memories,
                discover beautiful places and enjoy every moment.
              </p>

              <div style={styles.feature}>
                🌎 Explore beautiful destinations
              </div>

              <div style={styles.feature}>
                💸 Manage your travel budget
              </div>

              <div style={styles.feature}>
                🧳 Save your personal trips
              </div>

              <div style={styles.feature}>
                ❤️ Make unforgettable memories
              </div>

            </div>
          </div>

          {/* SAVED TRIP SUMMARY */}
          {planned && (
            <div style={styles.summary}>

              <h2>🎉 Your Trip Summary</h2>

              <div style={styles.summaryGrid}>

                <p>
                  <b>📍 Destination</b>
                  <br />
                  {destination}
                </p>

                <p>
                  <b>📅 Duration</b>
                  <br />
                  {days} days
                </p>

                <p>
                  <b>👥 Travelers</b>
                  <br />
                  {travelers}
                </p>

                <p>
                  <b>💰 Total Budget</b>
                  <br />
                  ₹{Number(budget).toLocaleString("en-IN")}
                </p>

              </div>

              <p style={{ color: "#16834a", marginTop: 12 }}>
                Your trip has been saved in the database!
              </p>

            </div>
          )}
        </>
      )}

    </div>
  );
}

